    OUTPUT_DIRECTORY.mkdir(parents=True, exist_ok=True)
    ledger = load_ledger()
    glossary = glossary_source_titles()
    print(f"— Phase A: {len(WIKIMEDIA_ASSETS)} Commons artworks —")
    for local_name, title in WIKIMEDIA_ASSETS.items():
        destination = OUTPUT_DIRECTORY / local_name
        if destination.exists():
            print(f"  skip (exists): {local_name}")
            continue

        # Gate 1 (pre-network): this exact file is already on tellmeohmuse
        glossary_key = glossary.get(normalize_commons_title(title))
        if glossary_key:
            print(f"  REFUSED {local_name}: already in the live glossary as "
                  f"{glossary_key!r} — remove it from WIKIMEDIA_ASSETS")
            continue

        # Gate 2 (pre-network): already arrived under another name/term
        if (hit := ledger_find(ledger, title=title)):
            print(f"  REFUSED {local_name}: same title already ingested as "
                  f"{hit['local_name']!r}")
            continue

        try:
            resolved = resolve_commons_file(title)
        except Exception as error:
            print(f"  FAIL resolving {title!r}: {error}")
            polite_pause()
            continue
        polite_pause()  # the API ping was a request too

        if resolved is None:
            print(f"  MISSING on Commons: {title!r} — fix the title in "
                  "WIKIMEDIA_ASSETS (search commons.wikimedia.org) and re-run")
            continue

        # Gate 3 (post-resolve, pre-download): identical bytes or same Commons
        # page already ingested under a DIFFERENT title (re-uploads, renames)
        if (hit := ledger_find(ledger, sha1=resolved["sha1"],
                               pageid=resolved["pageid"])):
            print(f"  REFUSED {local_name}: identical content already "
                  f"ingested as {hit['local_name']!r} (from {hit['title']!r})")
            continue

        rendition = (f"scaled to {MAX_LONG_EDGE}px from {resolved['width']}px"
                     if resolved["scaled"] else "original")
        print(f"  downloading {local_name}  [{resolved['license']}] ({rendition})")
        try:
            with requests.get(
                resolved["download_url"], headers=COMMONS_HEADERS, stream=True,
                timeout=120,
            ) as response:
                response.raise_for_status()
                partial = destination.with_suffix(destination.suffix + ".part")
                with open(partial, "wb") as fh:
                    for chunk in response.iter_content(chunk_size=1 << 16):
                        fh.write(chunk)
                partial.rename(destination)  # atomic: no half-files on interrupt
            ledger_record(ledger, local_name=local_name, title=title,
                          sha1=resolved["sha1"], pageid=resolved["pageid"],
                          license=resolved["license"])
        except Exception as error:
            print(f"  FAIL downloading {local_name}: {error}")
        polite_pause()


