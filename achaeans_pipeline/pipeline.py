#!/usr/bin/env python3
"""Multiverse Achaean Media Pipeline.

Two-pronged polite ingestion into ./achaeans_curated_library:

  Phase A ("art")   — Wikimedia Commons: resolve each File: title via the
                      MediaWiki Action API, then download the original.
  Phase B ("films") — Internet Archive: query each item's file manifest first,
                      download only companion images + the smallest usable MP4.
  Phase C ("clips") — Cut short clips from the downloaded MP4s with ffmpeg.
                      Runs ONLY for specs whose `start` timestamp has been set
                      (they ship as None so nobody cuts blind at 0:00).

  Phase 0 ("verify")   — resolve every manifest title via the API, download
                         NOTHING. The manifest titles were generated by an LLM
                         (Gemini) and are unverified guesses — run this first.
  Phase D ("discover") — keyword search of Commons, filtered to PD/CC-usable
                         licenses; writes a candidate manifest for review,
                         downloads NOTHING. Use it to repair MISSING manifest
                         titles or to scout new subjects.

  Phase E ("dedupe")   — no-duplicates audit: identity collisions across term
                         manifests, matches against the live glossary's
                         art.json, and a dHash+aHash perceptual sweep (the
                         thresholds proven on tellmeohmuse). Network-free.
                         Arrival-time PREVENTION is separate: the art phase
                         refuses downloads via the library ledger + glossary
                         gates before any bytes move.

Usage:
    python pipeline.py verify             # resolve manifest titles, no downloads
    python pipeline.py seed-ledger        # load the live glossary's Commons
                                          # identities into the ledger gate
    python pipeline.py                    # art + films (clips skipped until timed)
    python pipeline.py art
    python pipeline.py films
    python pipeline.py clips              # after filling in CLIP_SPECS timestamps
    python pipeline.py all
    python pipeline.py discover "mycenaean warrior"   # candidate manifest only
    python pipeline.py discover --terms-file terms.txt
    python pipeline.py select "Mask of Agamemnon"   # score + montage the top
                                          # candidates of one term's manifest
    python pipeline.py dedupe             # audit after every harvest batch

Politeness standard (mandatory, do not loosen):
  * 2.5 s sleep between EVERY remote request — API pings included.
  * Every download is skip-if-exists, so an interrupted re-run makes zero
    duplicate connections.
  * One explicit descriptive User-Agent on every Commons request.
"""

