def polite_pause() -> None:
    time.sleep(POLITENESS_DELAY_SECONDS)


def license_is_usable(license_name: str) -> bool:
    """Same acceptance bar as the glossary: PD / CC0 / CC-BY / CC-BY-SA only."""
    name = license_name.lower()
    if "nc" in name or "nd" in name:  # non-commercial / no-derivatives: reject
        return False
    return name.startswith(("public domain", "pd", "cc0", "cc by"))


# ── Phase A: Wikimedia Commons art ───────────────────────────────────────────

def resolve_commons_file(title: str) -> dict | None:
    """Ask the Action API for the original-file URL, license, and identity.

    Returns {"url", "license", "sha1", "pageid"} or None if the title
    doesn't exist. sha1/pageid feed the arrival-time duplicate gates.
    """
    response = requests.get(
        COMMONS_API,
        params={
            "action": "query",
            "titles": title,
            "prop": "imageinfo",
            "iiprop": "url|extmetadata|sha1|size",
            "iiurlwidth": str(MAX_LONG_EDGE),  # ask for a scaled rendition too
            "format": "json",
            "formatversion": "2",
        },
        headers=COMMONS_HEADERS,
        timeout=30,
    )
    response.raise_for_status()
    page = response.json()["query"]["pages"][0]
    if page.get("missing") or "imageinfo" not in page:
        return None
    info = page["imageinfo"][0]
    license_name = (
        info.get("extmetadata", {})
        .get("LicenseShortName", {})
        .get("value", "unknown")
    )
    oversized = (info.get("width") or 0) > MAX_LONG_EDGE
    return {
        "url": info["url"],
        "download_url": (info.get("thumburl") if oversized and
                         info.get("thumburl") else info["url"]),
        "scaled": oversized and bool(info.get("thumburl")),
        "width": info.get("width"),
        "license": license_name,
        "sha1": info.get("sha1"),
        "pageid": page.get("pageid"),
    }


# ── Library ledger: what has already arrived, by identity not filename ───────
# Written on every successful download; consulted BEFORE any download. This is
# the arrival-time duplicate gate — dedupe (Phase E) is the after-the-fact
# audit, the ledger is what stops a duplicate landing at all.

LEDGER_PATH = OUTPUT_DIRECTORY / "library_ledger.json"


def load_ledger() -> dict:
    if LEDGER_PATH.exists():
        return json.loads(LEDGER_PATH.read_text())
    return {"entries": []}


def ledger_record(ledger: dict, **entry) -> None:
    ledger["entries"].append(entry)
    LEDGER_PATH.write_text(json.dumps(ledger, indent=2, ensure_ascii=False))


def ledger_find(ledger: dict, *, sha1=None, pageid=None, title=None):
    normalized = normalize_commons_title(title) if title else None
    for entry in ledger["entries"]:
        if sha1 and entry.get("sha1") == sha1:
            return entry
        if pageid and entry.get("pageid") == pageid:
            return entry
        if normalized and normalize_commons_title(entry.get("title", "")) == normalized:
            return entry
    return None


